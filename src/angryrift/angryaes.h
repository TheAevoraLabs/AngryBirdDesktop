inline void AES_init_ctx_iv(struct AES_ctx* ctx, const uint8_t* key,
                            const uint8_t* iv) {
    angryaes_detail::KeyExpansion256(ctx->RoundKey, key);
    std::memcpy(ctx->Iv, iv, 16);
}
inline void AES_CBC_decrypt_buffer(struct AES_ctx* ctx, uint8_t* out,
                                   const uint8_t* in, uint32_t length) {
    uint8_t buf[16];
    for (uint32_t off = 0; off < length; off += 16) {
        std::memcpy(buf, in + off, 16);
        uint8_t blk[16];
        std::memcpy(blk, buf, 16);
        angryaes_detail::InvCipher(blk, ctx->RoundKey);
        for (int i = 0; i < 16; ++i) out[off + i] = (uint8_t)(blk[i] ^ ctx->Iv[i]);
        std::memcpy(ctx->Iv, buf, 16);
    }
}
