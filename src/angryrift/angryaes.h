inline void KeyExpansion256(uint8_t* RoundKey, const uint8_t* Key) {
    unsigned i, j, k;
    uint8_t tempa[4];
    for (i = 0; i < 8; ++i) {
        RoundKey[(i * 4) + 0] = Key[(i * 4) + 0];
        RoundKey[(i * 4) + 1] = Key[(i * 4) + 1];
        RoundKey[(i * 4) + 2] = Key[(i * 4) + 2];
        RoundKey[(i * 4) + 3] = Key[(i * 4) + 3];
    }
    for (i = 8; i < 4 * 15; ++i) {
        k = (i - 1) * 4;
        tempa[0] = RoundKey[k + 0];
        tempa[1] = RoundKey[k + 1];
        tempa[2] = RoundKey[k + 2];
        tempa[3] = RoundKey[k + 3];
        if (i % 8 == 0) {
            const uint8_t u8tmp = tempa[0];
            tempa[0] = tempa[1]; tempa[1] = tempa[2];
            tempa[2] = tempa[3]; tempa[3] = u8tmp;
            tempa[0] = kSbox[tempa[0]]; tempa[1] = kSbox[tempa[1]];
            tempa[2] = kSbox[tempa[2]]; tempa[3] = kSbox[tempa[3]];
            tempa[0] = tempa[0] ^ kRcon[i / 8];
        }
        if (i % 8 == 4) {
            tempa[0] = kSbox[tempa[0]]; tempa[1] = kSbox[tempa[1]];
            tempa[2] = kSbox[tempa[2]]; tempa[3] = kSbox[tempa[3]];
        }
        j = i * 4; k = (i - 8) * 4;
        RoundKey[j + 0] = RoundKey[k + 0] ^ tempa[0];
        RoundKey[j + 1] = RoundKey[k + 1] ^ tempa[1];
        RoundKey[j + 2] = RoundKey[k + 2] ^ tempa[2];
        RoundKey[j + 3] = RoundKey[k + 3] ^ tempa[3];
    }
}
inline void AddRoundKey(uint8_t round, uint8_t* state, const uint8_t* RK) {
    for (uint8_t i = 0; i < 4; ++i)
        for (uint8_t j = 0; j < 4; ++j)
            state[(i * 4) + j] ^= RK[(round * 16) + (i * 4) + j];
}
inline void InvShiftRows(uint8_t* s) {
    uint8_t t;
    t = s[13]; s[13] = s[9]; s[9] = s[5]; s[5] = s[1]; s[1] = t;
    t = s[2]; s[2] = s[10]; s[10] = t;
    t = s[6]; s[6] = s[14]; s[14] = t;
    t = s[3]; s[3] = s[7]; s[7] = s[11]; s[11] = s[15]; s[15] = t;
}
inline void InvSubBytes(uint8_t* s) {
    for (int i = 0; i < 16; ++i) s[i] = kRsbox[s[i]];
}
inline uint8_t Multiply(uint8_t x, uint8_t y) {
    return static_cast<uint8_t>(
        (((y & 1) * x) ^ ((y >> 1 & 1) * xtime(x)) ^
         ((y >> 2 & 1) * xtime(xtime(x))) ^
         ((y >> 3 & 1) * xtime(xtime(xtime(x)))) ^
         ((y >> 4 & 1) * xtime(xtime(xtime(xtime(x)))))));
}
inline void InvMixColumns(uint8_t* s) {
    for (int i = 0; i < 4; ++i) {
        uint8_t a = s[i*4+0], b = s[i*4+1], c = s[i*4+2], d = s[i*4+3];
        s[i*4+0] = Multiply(a,0x0e)^Multiply(b,0x0b)^Multiply(c,0x0d)^Multiply(d,0x09);
        s[i*4+1] = Multiply(a,0x09)^Multiply(b,0x0e)^Multiply(c,0x0b)^Multiply(d,0x0d);
        s[i*4+2] = Multiply(a,0x0d)^Multiply(b,0x09)^Multiply(c,0x0e)^Multiply(d,0x0b);
        s[i*4+3] = Multiply(a,0x0b)^Multiply(b,0x0d)^Multiply(c,0x09)^Multiply(d,0x0e);
    }
}
inline void InvCipher(uint8_t* s, const uint8_t* RK) {
    AddRoundKey(14, s, RK);
    for (int round = 13; ; --round) {
        InvShiftRows(s); InvSubBytes(s); AddRoundKey(round, s, RK);
        if (round == 0) break;
        InvMixColumns(s);
    }
}
